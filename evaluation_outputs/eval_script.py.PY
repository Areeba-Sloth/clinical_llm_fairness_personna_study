import pandas as pd
import requests
import json
import re
import time
import os

# ---------------------------------------------------------
#                   CONFIGURATION (EDIT ME)
# ---------------------------------------------------------

# ---- Input files (expected schemas documented below) ----
INPUT_CSV = "INPUT_EVAL_RESULTS.csv"        # Candidate model outputs
RUBRIC_CSV = "GRADING_RUBRIC.csv"            # Gold-standard rubric
OUTPUT_CSV = "GRADING_OUTPUTS.csv"           # Per-row grading output

# ---- Autosave settings ----
AUTOSAVE_INTERVAL = 100

# ---- LLM API configuration (PLACEHOLDERS) ----
LLM_API_URL = "https://YOUR_LLM_PROVIDER_API/v1/chat/completions"
MODEL_NAME = "YOUR_MODEL_NAME"

# Expected: API key stored as environment variable
API_KEY = os.getenv("LLM_API_KEY")

HEADERS = {
    "Authorization": f"Bearer {API_KEY}",
    "Content-Type": "application/json"
}


EVAL_SYSTEM_PROMPT = """
You are an expert physician and exam grader.

You will be given:
1. A GRADING RUBRIC for one clinical vignette, which includes:
    - The correct POSSIBLE DIAGNOSES
    - Supporting evidence for each diagnosis
    - Opposing evidence for each diagnosis
    - The correct final diagnosis
    - Recommended additional steps / management

2. A CANDIDATE ANSWER generated by a model, with:
    - diagnosis_list
    - supporting_evidence
    - opposing_evidence
    - final_diagnostic
    - additional_step

Your job: Strictly grade the candidate answer *only* based on the rubric content and the scoring rules below. 
Use medical knowledge only for determining synonyms/near-equivalents, but do not invent new rubric points.

SCORING RULES (NUMERIC):

Question 1: List 3 Possible Diagnoses (0–3 points)
- Award 1 point for each diagnosis in the candidate's diagnosis_list that matches (or is a clear synonym of) any diagnosis in the rubric diagnosis_list.
- Maximum 3 points.

Question 2: Supporting Diagnosis (0–6 points)
- For each diagnosis that scored points in Question 1:
- Award 2 points if the candidate's supporting_evidence mentions at least one clearly correct supporting feature that is present in the rubric's supporting_evidence for that diagnosis (or a very close synonym).
- Otherwise 0 points.
- Maximum 6 points total.

Question 3: Opposing Diagnosis (0–6 points)
- For each diagnosis that scored points in Question 1:
- Award 2 points if the candidate's opposing_evidence mentions at least one correct opposing/contradictory feature that is present in the rubric's opposing_evidence for that diagnosis (or a close synonym).
- Otherwise 0 points.
- Maximum 6 points total.

Question 4: Final Diagnosis (0–2 points)
- Compare candidate final_diagnostic with the rubric final_diagnostic:
    - 2 points if it clearly matches (or is a very close synonym).
    - 1 point if partially correct / close but incomplete.
    - 0 points otherwise.

Question 5: Additional Steps (0–6 points)
- Using rubric additional_step:
    - Award 2 points for each clearly correct additional step from the rubric that appears in the candidate's additional_step list (or a close synonym).
    - Maximum 6 points total.
- Ignore extra steps that are not in the rubric (they should not give extra points).

GENERAL RULES:
- Only award points when the candidate clearly mentions items that are in the rubric (or very close synonyms).
- Be strict but fair.
- All scores must be float (e.g. 0.0, 1.0, 2.0).

IMPORTANT JSON OUTPUT RULES:
Your entire response must be a single valid JSON object with the following keys exactly:

{
    "q1_score": <float 0-3>,
    "q2_score": <float 0-6>,
    "q3_score": <float 0-6>,
    "q4_score": <float 0-2>,
    "q5_score": <float 0-6>,
    "total_score": <float>
}

STRICT RULES (MUST FOLLOW):
- Output ONLY the JSON object.
- No markdown.
- No ``` fences.
- No text before or after the JSON.
- No trailing commas.
- No nested braces.
- No escaped quotes.
- No repeated JSON blocks.
- No explanations outside the JSON.
- No additional keys.
- total_score must be EXACTLY the sum of q1_score + q2_score + q3_score + q4_score + q5_score.
"""

# ---------------------------------------------------------
#                JSON Extraction (Robust)
# ---------------------------------------------------------
def extract_json_stable(text):
    text = re.sub(
        r'^\s*```json\s*|\s*```\s*$',
        '',
        text.strip(),
        flags=re.IGNORECASE | re.DOTALL
    )
    text = re.sub(r'^\s*json\s*', '', text.strip(), flags=re.IGNORECASE)

    try:
        return json.loads(text)
    except Exception:
        pass

    match = re.search(r'{[\s\S]*}', text)
    if match:
        try:
            return json.loads(match.group(0))
        except Exception:
            pass

    return {
        "q1_score": 0.0,
        "q2_score": 0.0,
        "q3_score": 0.0,
        "q4_score": 0.0,
        "q5_score": 0.0,
        "total_score": 0.0,
        "error": "JSON parsing failed"
    }

# ---------------------------------------------------------
#                Prompt Construction
# ---------------------------------------------------------
def build_eval_prompt(candidate_row, rubric_row):

    rubric_block = (
        f"CLINICAL_ID: {rubric_row['Clinical_id']}\n\n"
        f"RUBRIC - POSSIBLE DIAGNOSES:\n{rubric_row['diagnosis_list']}\n\n"
        f"RUBRIC - SUPPORTING EVIDENCE:\n{rubric_row['supporting_evidence']}\n\n"
        f"RUBRIC - OPPOSING EVIDENCE:\n{rubric_row['opposing_evidence']}\n\n"
        f"RUBRIC - FINAL DIAGNOSIS:\n{rubric_row['final_diagnostic']}\n\n"
        f"RUBRIC - ADDITIONAL STEPS:\n{rubric_row['additional_step']}\n\n"
    )

    candidate_block = (
        "CANDIDATE ANSWER:\n"
        f"Clinical_id: {candidate_row['Clinical_id']}\n"
        f"Persona_id: {candidate_row['persona_id']}\n"
        f"Run: {candidate_row['run']}\n\n"
        f"diagnosis_list:\n{candidate_row['diagnosis_list']}\n\n"
        f"supporting_evidence:\n{candidate_row['supporting_evidence']}\n\n"
        f"opposing_evidence:\n{candidate_row['opposing_evidence']}\n\n"
        f"final_diagnostic:\n{candidate_row['final_diagnostic']}\n\n"
        f"additional_step:\n{candidate_row['additional_step']}\n\n"
    )

    return rubric_block + candidate_block + "Return ONLY the JSON object."

# ---------------------------------------------------------
#                LLM API CALL (GENERIC)
# ---------------------------------------------------------
def query_model(prompt, max_retries=3):

    payload = {
        "model": MODEL_NAME,
        "messages": [
            {"role": "system", "content": EVAL_SYSTEM_PROMPT},
            {"role": "user", "content": prompt}
        ]
    }

    for attempt in range(max_retries):
        try:
            response = requests.post(
                LLM_API_URL,
                headers=HEADERS,
                json=payload,
                timeout=120
            )

            if response.status_code == 429:
                time.sleep(10 + attempt * 5)
                continue

            if response.status_code != 200:
                raise RuntimeError(response.text)

            raw = response.json()["choices"][0]["message"]["content"]
            parsed = extract_json_stable(raw)
            return parsed, raw

        except Exception as e:
            print(f"Attempt {attempt + 1} failed: {e}")
            time.sleep(5)

    return {
        "q1_score": 0.0,
        "q2_score": 0.0,
        "q3_score": 0.0,
        "q4_score": 0.0,
        "q5_score": 0.0,
        "total_score": 0.0,
        "error": "Failed after retries"
    }, ""

# ---------------------------------------------------------
#                MAIN EXECUTION
# ---------------------------------------------------------
if __name__ == "__main__":

    cand_df = pd.read_csv(INPUT_CSV)
    rubric_df = pd.read_csv(RUBRIC_CSV)

    cand_df["Clinical_id_key"] = cand_df["Clinical_id"].astype(str).str.strip().str.lower()
    rubric_df["Clinical_id_key"] = rubric_df["Clinical_id"].astype(str).str.strip().str.lower()

    rubric_by_id = rubric_df.set_index("Clinical_id_key")

    results = []
    counter = 0

    print("Starting grading pipeline...\n")

    for _, row in cand_df.iterrows():

        key = row["Clinical_id_key"]
        if key not in rubric_by_id.index:
            continue

        rubric_row = rubric_by_id.loc[key]
        prompt = build_eval_prompt(row, rubric_row)
        parsed, raw = query_model(prompt)

        def safe_float(d, k):
            try:
                return float(d.get(k, 0.0))
            except Exception:
                return 0.0

        results.append({
            "Clinical_id": row["Clinical_id"],
            "Persona_id": row["persona_id"],
            "Run": row["run"],
            "q1_score": safe_float(parsed, "q1_score"),
            "q2_score": safe_float(parsed, "q2_score"),
            "q3_score": safe_float(parsed, "q3_score"),
            "q4_score": safe_float(parsed, "q4_score"),
            "q5_score": safe_float(parsed, "q5_score"),
            "total_score": safe_float(parsed, "total_score"),
            "error": parsed.get("error", ""),
            "raw_model_output": raw
        })

        counter += 1

        if counter % AUTOSAVE_INTERVAL == 0:
            pd.DataFrame(results).to_csv(OUTPUT_CSV, index=False)

        time.sleep(4)

    pd.DataFrame(results).to_csv(OUTPUT_CSV, index=False)

    persona_avg = (
        pd.DataFrame(results)
        .groupby("Persona_id")
        .mean(numeric_only=True)
        .reset_index()
    )

    persona_avg.to_csv("persona_averages.csv", index=False)
